"""Check pyrio.geometry's wall table against the game's stadium collision models.

The table (pyrio/geometry/_data/walls.json) is generated by
derive_stadium_walls.py, so this is a regression check: it answers "does the
table still match the models?" after a hand-edit, a model-set update, or a
change to the generator. It changes nothing.

It reuses the generator's own extraction and its nearest_wall, rather than
re-deriving the geometry. An earlier version did its own cruder reading --
bucketing triangles by centroid x and comparing the minimum centroid z -- which
is off by roughly a panel's slope times its width, and so reported 1.4-4.3m
errors against a table that reproduces the models exactly. A checking tool that
cannot distinguish a real error from its own is worse than none.

Usage:
    python tools/compare_stadium_walls.py [path/to/stadium/models]

The models are the per-stadium JSON collision files (one per stadium, named
after it, each containing "Triangle Collections"). RioVisualizer keeps a set
under rio_visualizer/data/stadiums/; pass that directory, or set
PYRIO_STADIUM_MODELS.
"""

from __future__ import annotations

import importlib.util
import json
import os
import pathlib
import sys

_HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent / "src"))

_spec = importlib.util.spec_from_file_location("_derive", _HERE / "derive_stadium_walls.py")
assert _spec is not None
assert _spec.loader is not None
_derive = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_derive)

SAMPLES_PER_SEGMENT = 40


def table_wall_at(walls, stadium: str, x: float):
    """(wall_z, height) from a table table, or None if x has no segment.

    Mirrors pyrio.geometry.wall_at, including its `sx <= x < ex` matching, so
    what is checked is what callers actually get.
    """
    spec = walls.get(stadium)
    if spec is None:
        return None
    for sx, ex, h, m, c in zip(
        spec["starting_x"], spec["ending_x"], spec["wall_height"], spec["m"], spec["c"], strict=True
    ):
        if sx <= x < ex:
            return m * x + c, h
    return None


def compare(walls, stadium, lines, tris):
    """(worst_dz, worst_dh, n, worst_x) of the table against the model."""
    spec = walls[stadium]
    worst_dz = worst_dh = 0.0
    worst_x = None
    n = 0
    for sx, ex in zip(spec["starting_x"], spec["ending_x"], strict=True):
        margin = min(1e-3, 0.25 * (ex - sx))
        lo, hi = sx + margin, ex - margin
        for k in range(SAMPLES_PER_SEGMENT + 1):
            x = lo + (hi - lo) * k / SAMPLES_PER_SEGMENT
            truth = _derive.nearest_wall(lines, tris, x)
            table = table_wall_at(walls, stadium, x)
            if truth is None or table is None:
                continue
            dz, dh = abs(table[0] - truth[0]), abs(table[1] - truth[1])
            if dz > worst_dz or dh > worst_dh:
                worst_x = x
            worst_dz = max(worst_dz, dz)
            worst_dh = max(worst_dh, dh)
            n += 1
    return worst_dz, worst_dh, n, worst_x


def main(argv):
    models = pathlib.Path(argv[1] if len(argv) > 1 else os.environ.get("PYRIO_STADIUM_MODELS", ""))
    if not models.is_dir():
        print((__doc__ or "").strip().split("Usage:")[1].strip(), file=sys.stderr)
        return 2

    from pyrio import Stadium
    from pyrio.geometry import walls

    table = {
        s.label: {
            "starting_x": [w.start_x for w in walls(s)],
            "ending_x": [w.end_x for w in walls(s)],
            "wall_height": [w.height for w in walls(s)],
            "m": [w.slope for w in walls(s)],
            "c": [w.intercept for w in walls(s)],
        }
        for s in Stadium
    }

    print(f"{'stadium':16} {'in table':>8} {'max |dz|':>9} {'max |dh|':>9} {'samples':>8}  worst")
    worst_overall = 0.0
    seen = set()
    for path in sorted(models.glob("*.json")):
        stadium = path.stem
        seen.add(stadium)
        tris = _derive.wall_triangles(json.load(path.open()))
        lines = _derive.wall_lines(tris)
        if stadium not in table:
            print(
                f"{stadium:16} {'False':>8} {'-':>9} {'-':>9} {'-':>8}  "
                f"NO TABLE ENTRY ({len(lines)} wall lines in the model)"
            )
            continue
        if not lines:
            print(
                f"{stadium:16} {'True':>8} {'-':>9} {'-':>9} {'-':>8}  "
                f"no wall-typed triangles in the model"
            )
            continue
        dz, dh, n, wx = compare(table, stadium, lines, tris)
        worst_overall = max(worst_overall, dz, dh)
        where = f"x={wx:+.3f}" if wx is not None else "-"
        print(f"{stadium:16} {'True':>8} {dz:>9.3f} {dh:>9.3f} {n:>8}  {where}")

    for stadium in table:
        if stadium not in seen:
            print(
                f"{stadium:16} {'True':>8} {'-':>9} {'-':>9} {'-':>8}  IN TABLE BUT NO MODEL FILE"
            )

    print()
    if worst_overall <= 0.01:
        print(f"Table matches the models (worst deviation {worst_overall:.3f}).")
    else:
        print(
            f"Table DEVIATES from the models by up to {worst_overall:.3f}. "
            f"Regenerate with tools/derive_stadium_walls.py."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
